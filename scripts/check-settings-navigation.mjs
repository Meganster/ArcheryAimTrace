import assert from 'node:assert/strict';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.env.BASE_URL || 'http://127.0.0.1:4180';
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.body.dataset.appBuild === 'aim-pipeline-163');
  assert.equal(await page.locator('.tab-navigation button').count(), 4);
  for (const id of ['navBowShopBtn', 'navGuideBtn', 'demoBtn', 'zeroBtn', 'zeroYawBtn', 'captureAimBtn', 'gyroCalibrateBtn', 'levelRangeSlider']) {
    assert.equal(await page.locator(`#tabSettings #${id}`).count(), 1, `${id} is in Settings`);
    assert.equal(await page.locator(`#tabDashboard #${id}`).count(), 0);
  }
  assert.equal(await page.locator('#tabDashboard #orientationCanvas').count(), 1);
  await page.locator('#navSettingsBtn').click();
  assert.equal(await page.locator('#demoBtn').isVisible(), true);
  await page.locator('#demoBtn').click();
  await page.waitForFunction(() => document.getElementById('demoBtnText').textContent === 'Stop demo');
  await page.locator('#navCalibrationBtn').click();
  assert.equal(await page.locator('#zeroBtn').isVisible(), true);
  assert.equal(await page.locator('#demoBtn').isVisible(), false);
  await page.locator('#aimAxesVerified').check();
  await page.waitForFunction(() => !document.getElementById('captureAimBtn').disabled);
  await page.locator('#captureAimBtn').click();
  await page.waitForFunction(() => document.getElementById('aimStatus').textContent.includes('Relative aim active'));
  await page.locator('#navDashboardBtn').click();
  assert.equal(await page.locator('#tabDashboard').isVisible(), true);
  assert.equal(await page.locator('#zeroBtn').isVisible(), false);
  await page.locator('#navSettingsBtn').click();
  assert.equal(await page.locator('#tabCalibration').isVisible(), true, 'last Settings section retained');
  await page.locator('#navBowShopBtn').click();
  assert.equal(await page.locator('#tabBowShop').isVisible(), true);
  assert.equal(await page.locator('#navSettingsBtn').getAttribute('class'), 'nav-tab active');
  assert.equal(await page.locator('#tabCalibration').isVisible(), false);
  await page.waitForFunction(() => document.getElementById('bowShopCanvas').width > 1);
  await page.locator('#navGuideBtn').click();
  await page.waitForFunction(() => document.querySelector('#guideContent h1'));
  assert.equal(await page.locator('#tabGuide').isVisible(), true);
  assert.equal(await page.locator('#tabBowShop').isVisible(), false);
  await page.locator('#navSettingsGeneralBtn').click();
  await page.locator('#demoBtn').click();
  await page.waitForFunction(() => document.getElementById('demoBtnText').textContent === 'Demo');
  await page.locator('#navCalibrationBtn').click();
  await page.screenshot({ path: join(tmpdir(), 'openfloat-settings161-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#navBowShopBtn').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile Bow Shop fits');
  await page.locator('#navCalibrationBtn').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile Calibration fits');
  await page.screenshot({ path: join(tmpdir(), 'openfloat-settings161-mobile.png'), fullPage: true });
  await page.goto(`${base}/#/guide/reference/ble-commands`, { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('#guideContent h1'));
  assert.equal(await page.locator('#tabSettings').isVisible(), true);
  assert.equal(await page.locator('#tabGuide').isVisible(), true);
  assert.equal(await page.locator('#navGuideBtn').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#tabDashboard').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ nestedSettings: true, demo: true, capture: true, bowShop: true, guideDeepLink: true, mobile: true, errors }));
} finally { await browser.close(); }
